// ---- test mesh builders -----------------------------------------------------------------------

function box(sx, sy, sz) {
  const p = [
    0, 0, 0, sx, 0, 0, sx, sy, 0, 0, sy, 0,
    0, 0, sz, sx, 0, sz, sx, sy, sz, 0, sy, sz,
  ];
  const f = [
    0, 2, 1, 0, 3, 2, // bottom (facing -z)
    4, 5, 6, 4, 6, 7, // top
    0, 1, 5, 0, 5, 4, // front (y=0)
    1, 2, 6, 1, 6, 5, // right
    2, 3, 7, 2, 7, 6, // back
    3, 0, 4, 3, 4, 7, // left
  ];
  return orientOutward({ positions: Float32Array.from(p), indices: Uint32Array.from(f) });
}

// Revolve a profile [[r, z], ...] that starts and ends on the axis (r = 0) around Z.
function revolve(profile, segments) {
  const pos = [];
  const rings = profile.map(([r, z]) => {
    if (r === 0) { pos.push(0, 0, z); return { pole: pos.length / 3 - 1 }; }
    const start = pos.length / 3;
    for (let j = 0; j < segments; j++) {
      const a = (j / segments) * Math.PI * 2;
      pos.push(r * Math.cos(a), r * Math.sin(a), z);
    }
    return { start };
  });
  const idx = [];
  for (let i = 0; i + 1 < rings.length; i++) {
    const A = rings[i], B = rings[i + 1];
    for (let j = 0; j < segments; j++) {
      const j2 = (j + 1) % segments;
      if (A.pole !== undefined && B.pole !== undefined) continue;
      if (A.pole !== undefined) idx.push(A.pole, B.start + j2, B.start + j);
      else if (B.pole !== undefined) idx.push(A.start + j, A.start + j2, B.pole);
      else idx.push(A.start + j, A.start + j2, B.start + j2, A.start + j, B.start + j2, B.start + j);
    }
  }
  return orientOutward({ positions: Float32Array.from(pos), indices: Uint32Array.from(idx) });
}

function cup({ R = 40, H = 100, wall = 3, floor = 3, segments = 256, wallSteps = 30 } = {}) {
  const prof = [[0, 0]];
  for (let k = 1; k <= 4; k++) prof.push([(R * k) / 4, 0]);
  for (let k = 1; k <= wallSteps; k++) prof.push([R, (H * k) / wallSteps]);
  prof.push([R - wall, H]);
  for (let k = wallSteps - 1; k >= 0; k--) prof.push([R - wall, floor + ((H - floor) * k) / wallSteps]);
  for (let k = 3; k >= 1; k--) prof.push([((R - wall) * k) / 4, floor]);
  prof.push([0, floor]);
  return revolve(prof, segments);
}

function sphere(R = 15, rings = 32, segments = 48) {
  const prof = [[0, -R]];
  for (let i = 1; i < rings; i++) {
    const a = -Math.PI / 2 + (i / rings) * Math.PI;
    prof.push([R * Math.cos(a), R * Math.sin(a)]);
  }
  prof.push([0, R]);
  return revolve(prof, segments);
}

// ---- G-code helpers ---------------------------------------------------------------------------

function moves(gcode) {
  const out = [];
  for (const line of gcode.split('\n')) {
    const m = /^(G0|G1)\s/.exec(line);
    if (!m) continue;
    const get = (k) => { const r = new RegExp(`\\b${k}(-?[\\d.]+)`).exec(line); return r ? parseFloat(r[1]) : undefined; };
    out.push({ cmd: m[1], x: get('X'), y: get('Y'), z: get('Z'), e: get('E'), line });
  }
  return out;
}

function layerMoves(gcode, layer) {
  const start = gcode.indexOf(`;LAYER:${layer}\n`);
  const end = gcode.indexOf(`;LAYER:${layer + 1}\n`);
  return moves(gcode.slice(start, end === -1 ? undefined : end));
}

