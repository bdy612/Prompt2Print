test('test meshes are watertight', () => {
  for (const m of [box(20, 20, 20), cup(), sphere()]) {
    const a = analyzeMesh(m);
    assert.equal(a.watertight, true);
    assert.ok(!a.inverted);
  }
});

test('20 mm box: layers, markers, extrusion and bed bounds', () => {
  const bed = { x: 220, y: 220, z: 250 };
  const { gcode, stats } = sliceMesh(box(20, 20, 20), { printer: { bed } });
  assert.equal(stats.layers, 100);
  assert.deepEqual(stats.sizeMm, [20, 20, 20]);
  for (const marker of ['; generated by Prompt2Print built-in slicer', ';FLAVOR:Marlin', ';TIME:', ';Filament used:',
    ';LAYER_COUNT:100', 'G28', 'M83', 'G90', ';LAYER:0', ';LAYER:99', 'M84', 'M104 S0', 'M140 S0', 'M73 P']) {
    assert.ok(gcode.includes(marker), `missing ${marker}`);
  }
  const mv = moves(gcode);
  for (const m of mv) {
    if (m.cmd === 'G1' && m.e !== undefined && (m.x !== undefined || m.y !== undefined)) assert.ok(m.e > 0, `negative extrusion in print move: ${m.line}`);
    if (m.x !== undefined) assert.ok(m.x >= 0 && m.x <= bed.x, `X out of bed: ${m.line}`);
    if (m.y !== undefined) assert.ok(m.y >= 0 && m.y <= bed.y, `Y out of bed: ${m.line}`);
  }
  // model print moves stay inside the 20 mm footprint centred on the bed
  const l50 = layerMoves(gcode, 50).filter((m) => m.e > 0 && m.x !== undefined);
  assert.ok(l50.length > 0);
  for (const m of l50) {
    assert.ok(Math.abs(m.x - 110) <= 10.01 && Math.abs(m.y - 110) <= 10.01, `outside footprint: ${m.line}`);
  }
  // 8 cm³ box with 2 walls, 3/4 solid layers and 20 % infill: a few grams
  assert.ok(stats.filamentGrams > 2 && stats.filamentGrams < 8, `grams ${stats.filamentGrams}`);
  assert.ok(stats.printTimeSec > 300 && stats.printTimeSec < 3 * 3600, `time ${stats.printTimeSec}`);
  assert.ok(gcode.includes(`;TIME:${stats.printTimeSec}`));
});

test('infill percentage changes material use', () => {
  const m = box(30, 30, 30);
  const g0 = sliceMesh(m, { infillPercent: 0 }).stats.filamentGrams;
  const g20 = sliceMesh(m, { infillPercent: 20 }).stats.filamentGrams;
  const g100 = sliceMesh(m, { infillPercent: 100 }).stats.filamentGrams;
  assert.ok(g0 < g20 && g20 < g100, `${g0} ${g20} ${g100}`);
  // solid 27 cm³ PLA ≈ 33 g; allow for line overlap approximations
  assert.ok(g100 > 25 && g100 < 40, `solid grams ${g100}`);
});

test('mesh is centred on the bed and dropped to z=0', () => {
  const m = translateMesh(box(10, 10, 10), -500, 300, 42);
  const { gcode } = sliceMesh(m, { printer: { bed: { x: 200, y: 180, z: 200 } } });
  const l5 = layerMoves(gcode, 5).filter((mv) => mv.e > 0 && mv.x !== undefined);
  for (const mv of l5) assert.ok(Math.abs(mv.x - 100) <= 5.01 && Math.abs(mv.y - 90) <= 5.01);
  assert.ok(gcode.includes(';LAYER:49') && !gcode.includes(';LAYER:50\n'));
});

test('hollow cup: walls on the material side, fast enough', () => {
  const m = cup();
  assert.ok(m.indices.length / 3 > 30000, `triangles ${m.indices.length / 3}`);
  const t0 = Date.now();
  const { gcode, stats } = sliceMesh(m, {});
  const ms = Date.now() - t0;
  assert.ok(ms < 5000, `slicing took ${ms} ms`);
  assert.ok(Math.abs(stats.layers - 500) <= 1, `layers ${stats.layers}`);
  // mid-height layer: every printed point lies in the 3 mm wall ring
  const mid = layerMoves(gcode, 250).filter((mv) => mv.e > 0 && mv.x !== undefined);
  assert.ok(mid.length > 50);
  for (const mv of mid) {
    const r = Math.hypot(mv.x - 110, mv.y - 110);
    assert.ok(r >= 37 - 0.05 && r <= 40 + 0.05, `point at r=${r.toFixed(3)} outside the wall`);
  }
  // floor layers are solid discs: some extrusion line passes close to the centre
  const floor = layerMoves(gcode, 1);
  let px = null, py = null, nearCentre = false;
  for (const mv of floor) {
    if (mv.x === undefined) continue;
    if (mv.e > 0 && px !== null) {
      const dx = mv.x - px, dy = mv.y - py;
      const t = Math.max(0, Math.min(1, ((110 - px) * dx + (110 - py) * dy) / (dx * dx + dy * dy || 1)));
      if (Math.hypot(px + t * dx - 110, py + t * dy - 110) < 1) nearCentre = true;
    }
    px = mv.x; py = mv.y;
  }
  assert.ok(nearCentre, 'floor is not solid');
});

test('sphere: supports only when requested', () => {
  const m = sphere(15);
  const without = sliceMesh(m, { supports: false });
  const withS = sliceMesh(m, { supports: true });
  assert.ok(Math.abs(without.stats.layers - 150) <= 1);
  assert.ok(!without.gcode.includes(';TYPE:SUPPORT'));
  assert.ok(withS.gcode.includes(';TYPE:SUPPORT'));
  assert.ok(withS.stats.filamentGrams > without.stats.filamentGrams);
  // supports never print inside the sphere (centre at bed middle, z = 15)
  let type = '', z = 0, px = null, py = null, supportMoves = 0;
  for (const line of withS.gcode.split('\n')) {
    if (line.startsWith(';TYPE:')) { type = line.slice(6); continue; }
    if (line.startsWith(';LAYER:')) { type = ''; continue; }
    const [mv] = moves(line);
    if (!mv) continue;
    if (mv.z !== undefined && mv.x === undefined) { z = mv.z - 0.1; continue; }
    if (mv.x === undefined) continue;
    if (type === 'SUPPORT' && mv.e > 0 && px !== null) {
      supportMoves++;
      const rc = Math.sqrt(Math.max(0, 15 * 15 - (z - 15) ** 2));
      const dx = mv.x - px, dy = mv.y - py;
      const t = Math.max(0, Math.min(1, ((110 - px) * dx + (110 - py) * dy) / (dx * dx + dy * dy || 1)));
      const d = Math.hypot(px + t * dx - 110, py + t * dy - 110);
      assert.ok(d >= rc - 0.05, `support inside the model at z=${z.toFixed(2)}: d=${d.toFixed(2)} r=${rc.toFixed(2)}`);
    }
    px = mv.x; py = mv.y;
  }
  assert.ok(supportMoves > 20);
  const box20 = sliceMesh(box(20, 20, 20), { supports: true });
  assert.ok(!box20.gcode.includes(';TYPE:SUPPORT'));
  assert.ok(box20.stats.warnings.some((w) => /no overhangs/.test(w)));
});

test('flavors', () => {
  const m = box(15, 15, 5);
  const k = sliceMesh(m, { printer: { flavor: 'klipper' } }).gcode;
  assert.ok(k.includes('PRINT_START BED=60 EXTRUDER=210'));
  assert.ok(!k.includes('M73 '));
  const b = sliceMesh(m, { printer: { flavor: 'bambu', name: 'X1C' } }).gcode;
  assert.ok(b.includes('Bambu Studio or OrcaSlicer'));
  const petg = sliceMesh(m, { material: { code: 'PETG', nozzleTemp: 240, bedTemp: 80 } }).gcode;
  assert.ok(petg.includes('M109 S240') && petg.includes('M190 S80'));
});

test('oversized models produce a warning, open meshes are reported', () => {
  const big = sliceMesh(box(300, 20, 5), { printer: { bed: { x: 220, y: 220, z: 250 } } });
  assert.ok(big.stats.warnings.some((w) => /larger than/.test(w)));
  // remove one side triangle from a box → open mesh; the gap is wider than the closing tolerance
  const b = box(20, 20, 20);
  const ix = Array.from(b.indices);
  ix.splice(12, 3);
  const r = sliceMesh({ positions: b.positions, indices: Uint32Array.from(ix) }, {});
  assert.equal(r.stats.layers, 100);
  assert.ok(r.stats.warnings.some((w) => /not watertight/.test(w)), JSON.stringify(r.stats.warnings));
});

test('rejects empty meshes', () => {
  assert.throws(() => sliceMesh({ positions: new Float32Array(), indices: new Uint32Array() }));
});
